const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();

export function searchCars(query: string): Car[] {
  const q = norm(query);
  if (!q) return [];
  const words = q.split(" ");
  return cars
    .map((car) => {
      const hay = norm(
        [car.make, car.model, car.body, ...(car.aliases ?? [])].join(" "),
      );
      const full = norm(`${car.make} ${car.model}`);
      let score = 0;
      if (full === q) score += 100;
      if (full.startsWith(q)) score += 40;
      for (const w of words) if (hay.includes(w)) score += 10;
      return { car, score };
    })
    .filter((r) => r.score >= words.length * 10)
    .sort((a, b) => b.score - a.score)
    .map((r) => r.car);
}
